#!/usr/bin/env python3
"""Build a LaTeX results file for the E7 forward evaluation (D2, 2026-11-02).

Reads the JSON written by scripts/e7_evaluate.py and scripts/e7_formula.py and
writes manuscript/results_e7.tex. No number is typed by hand: every value comes
from the two JSON files. Decision strings are mapped to English only when they
are in DECISION_EN; any other string is printed verbatim and flagged on stderr.

REHEARSAL inputs are refused unless --allow-rehearsal is given; in that case the
output goes to a separate file whose every caption is stamped
"REHEARSAL -- NOT E7 RESULTS". Never \\input the REHEARSAL file in the manuscript.

Usage (D2, after both scripts have run once):
  python scripts/fill_e7_results.py --evaluate results_python/e7/<evaluate>.json \
      --formula results_python/e7/<formula>.json
"""
import argparse
import json
import math
import sys
from pathlib import Path

DECISION_EN = {
    "DIDUKUNG": "supported",
    "TIDAK TERKONFIRMASI": "not confirmed",
    "TIDAK TERBUKTI NON-INFERIOR": "non-inferiority not shown",
    "INFORMATIF": "informative",
}
_ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_",
        "$": r"\$", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}"}


def warn(msg):
    print("WARNING: " + msg, file=sys.stderr)


def esc(s):
    return "".join(_ESC.get(c, c) for c in str(s))


def num(x, nd=3):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "n/a"
    return f"{x:.{nd}f}".replace("-", "$-$")


def ci(pair, nd=3):
    if not isinstance(pair, (list, tuple)) or len(pair) != 2:
        sys.exit(f"ERROR: expected a 2-element CI, got {pair!r}")
    return "[" + num(pair[0], nd) + ", " + num(pair[1], nd) + "]"


def dec(s):
    if s in DECISION_EN:
        return DECISION_EN[s]
    warn(f"unmapped decision string {s!r}; printed verbatim")
    return esc(s)


def yn(b):
    return "yes" if b else "no"


def g(d, path):
    cur = d
    for k in path.split("/"):
        try:
            cur = cur[k]
        except (KeyError, TypeError):
            sys.exit(f"ERROR: missing key {path!r} (stopped at {k!r})")
    return cur


def table(label, caption, cols, header, rows, stamp, notes=None):
    out = [r"\begin{table}[htbp]", r"\centering", r"\small",
           "\\caption{" + stamp + caption + "}", "\\label{" + label + "}",
           "\\begin{tabular}{" + cols + "}", r"\hline",
           " & ".join(header) + r" \\", r"\hline"]
    out += [" & ".join(r) + r" \\" for r in rows]
    out += [r"\hline", r"\end{tabular}"]
    if notes:
        out.append("\\par\\smallskip{\\footnotesize " + notes + "}")
    out.append(r"\end{table}")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--evaluate", required=True, help="JSON from e7_evaluate.py")
    ap.add_argument("--formula", required=True, help="JSON from e7_formula.py")
    ap.add_argument("--out", default=None)
    ap.add_argument("--allow-rehearsal", action="store_true")
    ap.add_argument("--force", action="store_true", help="overwrite an existing output")
    a = ap.parse_args()

    ev = json.load(open(a.evaluate))
    fo = json.load(open(a.formula))

    reh_e = "REHEARSAL" in str(ev.get("mode", "")).upper()
    reh_f = "REHEARSAL" in str(fo.get("mode", "")).upper()
    if reh_e != reh_f:
        sys.exit(f"ERROR: mixed modes: evaluate={ev.get('mode')!r}, formula={fo.get('mode')!r}")
    if reh_e and not a.allow_rehearsal:
        sys.exit("ERROR: inputs are REHEARSAL output; refusing (use --allow-rehearsal for a stamped test file).")
    for k in ("minggu", "baris", "kelompok"):
        if ev.get(k) != fo.get(k):
            sys.exit(f"ERROR: evaluate and formula disagree on {k!r}: {ev.get(k)!r} vs {fo.get(k)!r}")

    out = Path(a.out or ("manuscript/results_e7_REHEARSAL.tex" if reh_e else "manuscript/results_e7.tex"))
    if out.exists() and not a.force:
        sys.exit(f"ERROR: {out} exists; pass --force to overwrite.")
    stamp = r"\textbf{REHEARSAL -- NOT E7 RESULTS.} " if reh_e else ""

    parts = ["% Generated by scripts/fill_e7_results.py -- do not edit by hand.",
             "% evaluate: " + a.evaluate, "% formula : " + a.formula,
             "% mode (evaluate): " + str(ev.get("mode")), "% mode (formula): " + str(fo.get("mode")),
             "\\newcommand{\\eSevenWeeks}{" + str(ev["minggu"]) + "}",
             "\\newcommand{\\eSevenRows}{" + str(ev["baris"]) + "}",
             "\\newcommand{\\eSevenClusters}{" + str(ev["kelompok"]) + "}",
             "\\newcommand{\\eSevenLambda}{" + num(ev.get("lambda"), 4) + "}",
             "% formula a,b,c = {}, {}, {}; n_train={}; cutoff={}".format(
                 g(fo, "formula/a"), g(fo, "formula/b"), g(fo, "formula/c"),
                 g(fo, "formula/n_train"), g(fo, "formula/cutoff")), ""]

    # Table 1: pre-registered tests (labels follow the frozen protocol)
    spec = [("P7a", "P7a/ss_hanfis_stabil", "P7a/ci95", "P7a/holm", "P7a/keputusan"),
            ("P7b", "P7b/ss_hibrida", "P7b/ci95", "P7b/holm", "P7b/keputusan")]
    rows = []
    for name, ss, c, h, d in spec:
        rows.append([name, num(g(ev, ss)), ci(g(ev, c)), num(g(ev, h + "/p_satu_sisi"), 4),
                     num(g(ev, h + "/ambang_holm"), 4), yn(g(ev, h + "/lolos")), dec(g(ev, d))])
    for name, base in (("P7e", "P7e_rumus_vs_persistence"), ("P7f", "P7f_hanfis_vs_rumus")):
        rows.append([name, num(g(fo, base + "/ss")), ci(g(fo, base + "/ci95")),
                     num(g(fo, base + "/holm/p_satu_sisi"), 4), num(g(fo, base + "/holm/ambang_holm"), 4),
                     yn(g(fo, base + "/holm/lolos")), dec(g(fo, base + "/keputusan"))])
    parts.append(table("tab:e7_primary", "E7 pre-registered tests (skill score, 95\\% interval, one-sided $p$, Holm threshold).",
                       "lccccll", ["Test", "Skill", "95\\% CI", "$p$", "Holm", "Pass", "Decision"], rows, stamp,
                       "Definitions follow the frozen protocol."))

    # Table 2: descriptive P7c and P7d
    meth = [("y_hanfis", "HANFIS"), ("y_lag4", "Persistence (lag 4)"), ("y_hibrida", "Hybrid"), ("y_ridge7", "Ridge-7")]
    rows = [[n, num(g(ev, "P7c_deskriptif/presisi_pada_20persen/" + k)),
             num(g(ev, "P7c_deskriptif/spearman_mingguan/" + k))] for k, n in meth]
    parts.append(table("tab:e7_p7c", "E7 descriptive (P7c): precision at 20\\% and weekly Spearman correlation. Hybrid minus persistence precision: "
                       + num(g(ev, "P7c_deskriptif/selisih_hibrida_minus_persistence")) + " "
                       + ci(g(ev, "P7c_deskriptif/ci95_selisih")) + "; decision: " + dec(g(ev, "P7c_deskriptif/keputusan")) + ".",
                       "lcc", ["Method", "Precision@20\\%", "Spearman (weekly)"], rows, stamp))
    rows = [[n, num(g(ev, "P7d/spearman_perubahan_mingguan/" + k)), ci(g(ev, "P7d/ci95/" + k))]
            for k, n in (("y_hanfis", "HANFIS"), ("y_ridge7", "Ridge-7"))]
    parts.append(table("tab:e7_p7d", "E7 secondary (P7d): Spearman correlation of weekly change; decision: " + dec(g(ev, "P7d/keputusan")) + ".",
                       "lcc", ["Method", "Spearman", "95\\% CI"], rows, stamp))
    parts.append("% P7d note (Indonesian, translate): " + str(g(ev, "P7d/catatan")))

    # Table 3: skill scores of all methods
    rows = [[n, num(g(ev, "ss_semua_metode/" + k + "/ss")), ci(g(ev, "ss_semua_metode/" + k + "/ci95"))]
            for k, n in (("y_hanfis", "HANFIS"), ("y_hibrida", "Hybrid"), ("y_ridge7", "Ridge-7"))]
    rows.append(["HANFIS vs persistence (formula run)", num(g(fo, "deskriptif_hanfis_vs_persistence/ss")),
                 ci(g(fo, "deskriptif_hanfis_vs_persistence/ci95"))])
    parts.append(table("tab:e7_allmethods", "E7 skill score of all methods relative to persistence (descriptive).",
                       "lcc", ["Method", "Skill", "95\\% CI"], rows, stamp))

    # Table 4: strata by input change
    rows = []
    for s, n in (("ada_perubahan_masukan", "Inputs changed"), ("tanpa_perubahan_masukan", "Inputs unchanged")):
        for k, m in (("y_hanfis", "HANFIS"), ("y_hibrida", "Hybrid")):
            rows.append([n, str(g(ev, "strata_deskriptif/" + s + "/baris")), m,
                         num(g(ev, "strata_deskriptif/" + s + "/" + k + "/ss")),
                         ci(g(ev, "strata_deskriptif/" + s + "/" + k + "/ci95"))])
    parts.append(table("tab:e7_strata", "E7 descriptive strata by input change; rows with unknown change excluded: "
                       + str(g(ev, "strata_deskriptif/baris_perubahan_tidak_diketahui_dikecualikan")) + ".",
                       "llccc", ["Stratum", "Rows", "Method", "Skill", "95\\% CI"], rows, stamp))

    # Table 5: sensitivity
    rows = [["Hybrid, $\\lambda$ of fold " + str(i), num(g(ev, "sensitivitas_deskriptif/ss_hibrida_lambda_fold_" + str(i))), ""] for i in range(5)]
    rows += [["HANFIS, log1p", num(g(ev, "sensitivitas_deskriptif/ss_hanfis_log1p")), ""],
             ["Hybrid, log1p", num(g(ev, "sensitivitas_deskriptif/ss_hibrida_log1p")), ""],
             ["Hybrid, without wordpress", num(g(ev, "sensitivitas_deskriptif/ss_hibrida_tanpa_wordpress")), ""]]
    for k, n in (("rumus_vs_persistence", "Formula vs persistence, weekly bootstrap"), ("hanfis_vs_rumus", "HANFIS vs formula, weekly bootstrap")):
        rows.append([n, num(g(fo, "sensitivitas_bootstrap_per_minggu/" + k + "/ss")),
                     ci(g(fo, "sensitivitas_bootstrap_per_minggu/" + k + "/ci95"))])
    parts.append(table("tab:e7_sens", "E7 sensitivity analyses (descriptive).", "lcc", ["Analysis", "Skill", "95\\% CI"], rows, stamp))
    parts.append("% formula-run note (Indonesian, translate): " + str(fo.get("catatan", "")) + " | "
                 + str(g(fo, "sensitivitas_bootstrap_per_minggu/catatan")))

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    print("wrote", out, "(REHEARSAL)" if reh_e else "")


if __name__ == "__main__":
    main()